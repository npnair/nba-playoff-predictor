"""Copy data/*.csv into docs/js/data.js so the web app uses the same inputs as the Python model.

Run after editing any CSV:
    python scripts/build_web_data.py --as-of "Nov 2, 2026"
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import asdict
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from predictor.data_io import load_all  # noqa: E402

OUT = ROOT / "docs" / "js" / "data.js"


def to_js(payload: dict) -> str:
    """Readable JSON with one game or player per line, so daily diffs stay small."""
    parts = []
    for key, value in payload.items():
        if key in ("games", "players"):
            rows = ",\n  ".join(json.dumps(r, ensure_ascii=False, separators=(",", ":")) for r in value)
            parts.append(f' "{key}": [\n  {rows}\n ]' if value else f' "{key}": []')
        else:
            body = json.dumps(value, indent=1, ensure_ascii=False).replace("\n", "\n ")
            parts.append(f' "{key}": {body}')
    return "{\n" + ",\n".join(parts) + "\n}"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    today = date.today()
    p.add_argument("--as-of", default=f"{today:%b} {today.day}, {today.year}", help="label shown on the page")
    args = p.parse_args()

    teams, injuries, moves = load_all()
    from predictor.data_io import load_games, load_players
    payload = {
        "asOf": args.as_of,
        "teams": [asdict(t) for t in teams],
        "injuries": [asdict(j) for j in injuries],
        "moves": [asdict(m) for m in moves],
        "games": [[g["date"], g["home"], g["away"], g["home_pts"], g["away_pts"]] for g in load_games()],
        "players": [[p["team"], p["bref_id"], p["player"], p["pos"], p["mpg"], p["bpm"], p["minutes"]]
                    for p in load_players()],
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/build_web_data.py from data/*.csv. Edit the CSVs, not this file.\n"
        f"window.PL_DATA = {to_js(payload)};\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(teams)} teams, {len(injuries)} injuries, {len(moves)} moves")


if __name__ == "__main__":
    main()
